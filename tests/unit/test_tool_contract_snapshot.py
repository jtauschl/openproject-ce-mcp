# Mirrors config.py's own OPENPROJECT_ENABLE_<SCOPE>_WRITE naming convention
# (see Settings.from_env/WRITE_GROUP_REQUIREMENTS) -- no public
# WRITE_SCOPE_ENV_VAR export exists to reuse, unlike READ_SCOPE_ENV_VAR.
_ALL_WRITE_SCOPES = frozenset(tools.WRITE_TOOLS_BY_SCOPE) | {"personal"}
_WRITE_SCOPE_ENV_VAR: dict[str, str] = {
    scope: f"OPENPROJECT_ENABLE_{scope.upper()}_WRITE" for scope in _ALL_WRITE_SCOPES
}

# scope -> its paired read env var, per WRITE_GROUP_REQUIREMENTS -- the same
# real invariant Settings.from_env enforces at startup (a write flag on
# without its matching read flag is a ConfigError). Used below so every
# write-scope tool's capability_env_vars records BOTH, not just the write
# flag: if that from_env enforcement were ever weakened/removed,
# enabled_tool_names() would still register the tool with read disabled
# (it only checks write_enabled(scope) itself), a real capability-gate
# regression this schema-drift gate must be able to catch.
_WRITE_SCOPE_PAIRED_READ_ENV_VAR: dict[str, str] = {
    write_key.removesuffix("_write"): read_env_var for write_key, _, _, read_env_var in WRITE_GROUP_REQUIREMENTS
}


def _classify() -> dict[str, tuple[str, str, tuple[str, ...]]]:
    """tool name -> (classification, scope, capability_env_vars), derived
    from tools.py's classification tables -- the same tables
    test_tool_groups.py already proves partition the full tool set with no
    overlaps or gaps.

    `capability_env_vars` also folds in `tools.ADDITIONAL_READ_SCOPES_BY_TOOL`
    for any tool listed there -- a tool's home scope alone understates its
    real registration requirements for these (e.g.
    `get_project_work_package_context`'s home scope is "project", but
    `enabled_tool_names()` additionally requires work_package AND version
    read). Omitting these env vars here would let a real capability-gate
    change to one of these tools drift unnoticed past this schema-drift gate
    -- exactly what OPM-2707 exists to catch."""
    classification: dict[str, tuple[str, str, tuple[str, ...]]] = {}
    for scope, names in tools.READ_TOOLS_BY_SCOPE.items():
        for name in names:
            classification[name] = ("read", scope, (READ_SCOPE_ENV_VAR[scope],))
    for scope, names in tools.WRITE_TOOLS_BY_SCOPE.items():
        for name in names:
            classification[name] = (
                "write",
                scope,
                (_WRITE_SCOPE_ENV_VAR[scope], _WRITE_SCOPE_PAIRED_READ_ENV_VAR[scope]),
            )
    for name in tools.PERSONAL_MUTATION_TOOLS:
        classification[name] = (
            "write",
            "personal",
            (READ_SCOPE_ENV_VAR["personal"], _WRITE_SCOPE_ENV_VAR["personal"]),
        )
    for name in tools.WORK_PACKAGE_UPLOAD_TOOLS:
        classification[name] = (
            "write",
            "work_package",
            (
                _WRITE_SCOPE_ENV_VAR["work_package"],
                _WRITE_SCOPE_PAIRED_READ_ENV_VAR["work_package"],
                "OPENPROJECT_ATTACHMENT_ROOT",
            ),
        )
    for name in tools.CONTAINER_UPLOAD_TOOLS:
        classification[name] = (
            "write",
            "|".join(tools.CONTAINER_UPLOAD_WRITE_SCOPES),
            ("OPENPROJECT_ATTACHMENT_ROOT",),
        )
    for name, additional_scopes in tools.ADDITIONAL_READ_SCOPES_BY_TOOL.items():
        kind, scope, env_vars = classification[name]
        additional_env_vars = tuple(READ_SCOPE_ENV_VAR[s] for s in sorted(additional_scopes))
        classification[name] = (kind, scope, tuple(dict.fromkeys(env_vars + additional_env_vars)))
    return classification


