def test_tool_contract_unchanged(name: str, live_catalog: dict[str, Any]) -> None:
    tool = live_catalog[name]
    expected = TOOL_CONTRACT_SNAPSHOT[name]

    assert tool.input_schema == expected["input_schema"], f"{name}: inputSchema changed"
